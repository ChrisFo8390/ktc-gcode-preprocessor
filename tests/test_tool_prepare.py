# Run from the repository root:
#   python3 -m unittest discover -s tests -v

import importlib
import logging
import os
import shutil
import sys
import tempfile
import unittest

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTRAS = os.path.join(REPO, 'klipper', 'extras')
sys.path.append(EXTRAS)

from gcode_preprocessor_base import PreprocessorContext, ProcessorConfig, run_pipeline  # noqa: E402

tool_prepare = importlib.import_module('preprocessors.tool_prepare')

LOG = logging.getLogger('test_tool_prepare')
LOG.addHandler(logging.NullHandler())
LOG.propagate = False

# Shaped like PrusaSlicer 2.9.6+BOSS output (Cali-Dragon): initial tool T4,
# the first use of T3/T0 only unretracts the travel retraction (E1)
SAMPLE = """; generated by PrusaSlicer 2.9.6 on 2026-10-11
PRINT_START TOOL_TEMP=220 T0_TEMP=220 T3_TEMP=220 T4_TEMP=220 BED_TEMP=70 TOOL=4
M83 ; use relative distances for extrusion
T4 ; change tool
M109 S220 T4
G1 E-1 F2100
G1 X163 Y122
G1 E1 F2100
G1 X170 Y122 E1.2
M104 S225 T3 ; preheat T3 time: 15s
G1 E-10 F2100
T3 ; change tool
M109 S225 T3
G1 X149 Y137 F54000
G1 E1 F2100
G1 X150 Y137 E0.5
G1 E-10 F2100
T4 ; change tool
G1 X151 Y137 F54000
G1 E10 F2100
G1 X152 Y137 E0.5
G1 E-10 F2100
T0 ; change tool
G1 X10 Y10 F54000
G1 X11 Y10 E0.5
T3 ; change tool
G1 E10 F2100
PRINT_END
; retract_length_toolchange = 10,10,10,10,10
; filament_retract_length_toolchange = nil,nil,nil,8,nil
; temperature = 225,225,225,230,225
"""


def processor(**values):
    return tool_prepare.create_processor(ProcessorConfig('tool_prepare', values, LOG), LOG)


def tokens():
    return importlib.import_module('preprocessors.token_replacer').create_processor(
        ProcessorConfig('tokens', {}, LOG), LOG)


class ProcessorTests(unittest.TestCase):
    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()

    def tearDown(self):
        shutil.rmtree(self.tmpdir)

    def run_on(self, text, processors):
        path = os.path.join(self.tmpdir, 'test.gcode')
        with open(path, 'w') as f:
            f.write(text)
        context = PreprocessorContext()
        context.file_path, context.filename = path, 'test.gcode'
        result = run_pipeline(path, processors, context, LOG)
        self.assertTrue(result['success'], result)
        with open(path) as f:
            return f.read().splitlines()

    def test_set_line_before_print_start(self):
        lines = self.run_on(SAMPLE, [tokens(), processor()])
        i = next(i for i, l in enumerate(lines) if l.startswith('PRINT_START'))
        # T3 uses the filament override (8), the others the printer value (10)
        self.assertEqual(lines[i - 1], '_KTC_PREPARE_TOOLS_SET TOOLS=4,3,0 TEMPS=225,230,225 '
                                       'RETRACT=10,8,10 INITIAL=4')

    def test_first_unretract_per_tool_extended(self):
        lines = self.run_on(SAMPLE, [tokens(), processor()])
        # Initial tool T4: unchanged (the print start purge primes it)
        self.assertIn('G1 E1 F2100', lines)
        # First use of T3: E1 + 8
        self.assertIn('G1 E9 F2100 ; +8 tool_prepare retraction', lines)
        # Later uses unchanged
        self.assertEqual(lines.count('G1 E10 F2100'), 2)
        # T0 extrudes without an unretract: the retraction is pushed before the move
        i = lines.index('G1 X11 Y10 E0.5')
        self.assertEqual(lines[i - 1], 'G1 E10 F2100 ; tool_prepare retraction')

    def test_fixed_retract_length(self):
        lines = self.run_on(SAMPLE, [tokens(), processor(retract_length='5')])
        self.assertTrue(any('RETRACT=5,5,5' in l for l in lines))
        self.assertIn('G1 E6 F2100 ; +5 tool_prepare retraction', lines)

    def test_absolute_extrusion_only_set_line(self):
        lines = self.run_on(SAMPLE.replace('M83 ;', 'M82 ;'), [tokens(), processor()])
        self.assertTrue(any(l.startswith('_KTC_PREPARE_TOOLS_SET') for l in lines))
        self.assertFalse(any('tool_prepare retraction' in l for l in lines))

    def test_without_token_replacer_nothing_changes(self):
        lines = self.run_on(SAMPLE, [processor()])
        self.assertFalse(any('_KTC_PREPARE_TOOLS_SET' in l for l in lines))


# --- Runtime with fake Klipper objects -----------------------------------

class FakeReactor:
    def monotonic(self):
        return 0.


class FakeLane:
    def __init__(self, tool, tool_loaded, load=True):
        self.status = {'map': f'T{tool}', 'tool_loaded': tool_loaded, 'load': load}

    def get_status(self, eventtime):
        return dict(self.status)


class FakeAFC:
    def __init__(self, lanes):
        self.lanes = lanes
        self.poop, self.poop_cmd = True, 'AFC_POOP'
        self.wipe, self.wipe_cmd = True, 'AFC_BRUSH'


class CommandError(Exception):
    pass


class FakeGcode:
    error = CommandError

    def __init__(self, afc):
        self.commands, self.scripts, self.afc = {}, [], afc

    def register_command(self, name, func, desc=None):
        self.commands[name] = func

    def run_script_from_command(self, script):
        self.scripts.append(script)
        # AFC's T<n> loads a lane that is not in the extruder yet
        if script.startswith('T') and script[1:].isdigit():
            lane = self.afc.lanes.get(f'lane{script[1:]}')
            if lane is not None and lane.status['load']:
                lane.status['tool_loaded'] = True


class FakePrinter:
    def __init__(self, objects):
        self.objects = objects

    def get_reactor(self):
        return FakeReactor()

    def lookup_object(self, name, default=None):
        return self.objects.get(name, default)


class FakeConfig:
    def __init__(self, printer):
        self.printer = printer

    def get_printer(self):
        return self.printer

    def get_name(self):
        return 'gcode_preprocessor tool_prepare'


class FakeGcmd:
    def __init__(self, **params):
        self.params = {k: str(v) for k, v in params.items()}
        self.responses = []

    def get(self, name, default=None):
        return self.params.get(name, default)

    def get_int(self, name, default=None, minval=None):
        return int(self.params[name]) if name in self.params else default

    def get_float(self, name, default=None, minval=None):
        return float(self.params[name]) if name in self.params else default

    def respond_info(self, msg):
        self.responses.append(msg)

    def error(self, msg):
        return CommandError(msg)


class RuntimeTests(unittest.TestCase):
    def make(self, lanes, **options):
        self.afc = FakeAFC(lanes)
        self.gcode = FakeGcode(self.afc)
        printer = FakePrinter({'gcode': self.gcode, 'AFC': self.afc})
        runtime = tool_prepare.ToolPrepareRuntime(FakeConfig(printer), options)
        runtime.cmd_SET(FakeGcmd(TOOLS='4,3,0', TEMPS='225,225,225', RETRACT='10,10,10', INITIAL=4))
        return runtime

    def test_heating_plan(self):
        self.assertEqual(tool_prepare.heating_plan([3, 0, 4], 2), [(3, None), (0, None), (4, 3)])
        self.assertEqual(tool_prepare.heating_plan([3, 0, 4], 0), [(3, None), (0, None), (4, None)])

    def test_prepare_sequence(self):
        runtime = self.make({'lane0': FakeLane(0, True), 'lane3': FakeLane(3, False),
                             'lane4': FakeLane(4, False)})
        runtime.cmd_KTC_PREPARE_TOOLS(FakeGcmd())
        s = self.gcode.scripts
        # Staggered heating: T3, 10 s, T0, 10 s, wait for T3, then T4
        self.assertEqual(s[:6], [
            'SET_HEATER_TEMPERATURE HEATER=extruder3 TARGET=225', 'G4 P10000',
            'SET_HEATER_TEMPERATURE HEATER=extruder TARGET=225', 'G4 P10000',
            'TEMPERATURE_WAIT SENSOR=extruder3 MINIMUM=223',
            'SET_HEATER_TEMPERATURE HEATER=extruder4 TARGET=225'])
        rest = s[6:]
        # T3 not loaded: AFC loads and purges, we only retract and set standby
        i = rest.index('T3')
        self.assertNotIn('AFC_POOP EXTRUDER=extruder3', rest)
        self.assertIn('G1 E-10 F2100', rest[i + 2])
        self.assertEqual(rest[i + 3], 'SET_HEATER_TEMPERATURE HEATER=extruder3 TARGET=0')
        # T0 already loaded: purged and brushed by us
        i = rest.index('T0')
        self.assertEqual(rest[i + 2:i + 4], ['AFC_POOP EXTRUDER=extruder', 'AFC_BRUSH EXTRUDER=extruder'])
        # Initial tool last, loaded by AFC, retracted, keeps its temperature
        self.assertEqual(rest[-3], 'T4')
        self.assertIn('G1 E-10', rest[-1])
        self.assertIsNone(runtime.data)

    def test_loaded_initial_tool_untouched(self):
        runtime = self.make({'lane0': FakeLane(0, True), 'lane3': FakeLane(3, True),
                             'lane4': FakeLane(4, True)}, max_heating='0', heat_stagger='0')
        runtime.cmd_KTC_PREPARE_TOOLS(FakeGcmd())
        s = self.gcode.scripts
        i = s.index('T4')
        self.assertEqual(s[i + 1:], ['TEMPERATURE_WAIT SENSOR=extruder4 MINIMUM=223'])

    def test_empty_lane_aborts_before_heating(self):
        runtime = self.make({'lane0': FakeLane(0, True), 'lane3': FakeLane(3, False, load=False),
                             'lane4': FakeLane(4, True)})
        with self.assertRaises(CommandError):
            runtime.cmd_KTC_PREPARE_TOOLS(FakeGcmd())
        self.assertEqual(self.gcode.scripts, [])

    def test_without_data_skipped(self):
        runtime = self.make({})
        runtime.data = None
        gcmd = FakeGcmd()
        runtime.cmd_KTC_PREPARE_TOOLS(gcmd)
        self.assertIn('skipped', gcmd.responses[0])
        self.assertEqual(self.gcode.scripts, [])


if __name__ == '__main__':
    unittest.main()
