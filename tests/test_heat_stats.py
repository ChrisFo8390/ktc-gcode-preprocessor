from gcode_preprocessor_base import PreprocessorContext, ProcessorConfig, run_pipeline  # noqa: E402

heat_stats = importlib.import_module('preprocessors.heat_stats')

LOG = logging.getLogger('test_heat_stats')
LOG.addHandler(logging.NullHandler())
LOG.propagate = False

# Shaped like PrusaSlicer 2.9.6+BOSS output with ooze prevention
SAMPLE = """; generated by PrusaSlicer 2.9.6+BOSS on 2026-10-10
M83
PRINT_START TOOL=0
M104 S225 T0 ; set new tool temperature
T0 ; change tool
M109 S220 T0 ; set temperature and wait
;LAYER_CHANGE
G1 Z.2 F600
G1 X10 Y10 E1.5
M104 S225 T1 ; preheat T1 time: 15s
G1 X20 Y10 E1.5
G1 E-15 F2100
M104 S125 T0 ; set temperature ;cooldown
M104 S225 T1 ; set new tool temperature so it can start heating while changing
T1 ; change tool
M107
M109 S225 T1 ; set temperature and wait for it to be reached
G1 X30 Y30 F54000
G1 E15 F2100
G1 X40 Y30 E1.2
T0 ; change tool
G1 X50 Y50 F54000
G1 X60 Y50 E1.0
PRINT_END
"""


def processor(**values):
    return heat_stats.create_processor(ProcessorConfig('heat_stats', values, LOG), LOG)


class ProcessorTests(unittest.TestCase):
    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()

    def tearDown(self):
        shutil.rmtree(self.tmpdir)

    def run_on(self, text, processors):
        path = os.path.join(self.tmpdir, 'test.gcode')
        with open(path, 'w') as f:
            f.write(text)
        context = PreprocessorContext()
        context.file_path, context.filename = path, 'test.gcode'
        result = run_pipeline(path, processors, context, LOG)
        self.assertTrue(result['success'], result)
        with open(path) as f:
            return f.read().splitlines()

    def test_marker_positions(self):
        lines = self.run_on(SAMPLE, [processor()])
        # Fingerprint, then RESET before the first command
        self.assertEqual(lines[2], '_KTC_HEAT_MARK EVENT=RESET')
        self.assertEqual(lines[3], 'M83')
        # Initial tool selection is not measured
        self.assertEqual(lines.count('_KTC_HEAT_MARK EVENT=BEGIN T=0'), 1)
        i = lines.index('M104 S225 T1 ; preheat T1 time: 15s')
        self.assertEqual(lines[i - 1], '_KTC_HEAT_MARK EVENT=PREHEAT T=1 TARGET=225 LEAD=15')
        i = lines.index('T1 ; change tool')
        self.assertEqual(lines[i - 1], '_KTC_HEAT_MARK EVENT=BEGIN T=1')
        i = lines.index('M109 S225 T1 ; set temperature and wait for it to be reached')
        self.assertEqual(lines[i + 1], '_KTC_HEAT_MARK EVENT=END T=1')
        # No wait after the second change: END before the first move
        i = lines.index('G1 X50 Y50 F54000')
        self.assertEqual(lines[i - 1], '_KTC_HEAT_MARK EVENT=END T=0')
        self.assertEqual(lines[-1], '_KTC_HEAT_MARK EVENT=REPORT')
        self.assertEqual(sum(1 for line in lines if line.startswith('_KTC_HEAT_MARK')), 7)

    def test_no_report_option(self):
        lines = self.run_on(SAMPLE, [processor(insert_report='False')])
        self.assertNotIn('_KTC_HEAT_MARK EVENT=REPORT', lines)

    def test_single_tool_print_unchanged(self):
        text = "M83\nT0\nG1 X1 Y1 E1\nG1 X2 Y1 E1\n"
        lines = self.run_on(text, [processor()])
        self.assertFalse(any('_KTC_HEAT_MARK' in line for line in lines))

    def test_with_other_processors(self):
        tokens = importlib.import_module('preprocessors.token_replacer').create_processor(
            ProcessorConfig('t', {}, LOG), LOG)
        idle = importlib.import_module('preprocessors.idle_tool_shutdown').create_processor(
            ProcessorConfig('i', {}, LOG), LOG)
        lines = self.run_on(SAMPLE, [tokens, idle, processor()])
        self.assertEqual(sum(1 for line in lines if line.startswith('_KTC_HEAT_MARK')), 7)
        # End-of-use shutdown of T1 (inserted after T0) and the markers coexist
        self.assertTrue(any(line.startswith('M104 T1 S0') for line in lines))

    def test_file_without_trailing_newline(self):
        lines = self.run_on(SAMPLE.rstrip('\n'), [processor()])
        self.assertEqual(lines[-2], 'PRINT_END')
        self.assertEqual(lines[-1], '_KTC_HEAT_MARK EVENT=REPORT')


# --- Runtime with fake Klipper objects -----------------------------------

class FakeReactor:
    NEVER = 9999999999999999.
    NOW = 0.

    def __init__(self):
        self.now = 0.
        self.timers = []

    def monotonic(self):
        return self.now

    def register_timer(self, callback, waketime):
        timer = [callback, waketime]
        self.timers.append(timer)
        return timer

    def update_timer(self, timer, waketime):
        timer[1] = waketime

    def advance(self, until):
        """Run due timers until the given time"""
        while True:
            timer = min(self.timers, key=lambda t: t[1])
            if timer[1] > until:
                break
            self.now = timer[1]
            timer[1] = timer[0](self.now)
        self.now = until


class FakeHeater:
    def __init__(self, temp, target):
        self.temp, self.target, self.rate = temp, target, 0.
        self.settled_at = 0.

    def get_temp(self, eventtime):
        return self.temp, self.target

    def check_busy(self, eventtime):
        # Like PID: busy outside +-1 °C or until the slope has settled
        return abs(self.target - self.temp) > 1. or eventtime < self.settled_at


class FakeToolhead:
    def __init__(self):
        self.moving = True
        self.print_time = None

    def check_busy(self, eventtime):
        # Busy: motion queued beyond now; standstill: queue ran dry
        if self.moving:
            return eventtime + 1., eventtime, False
        if self.print_time is not None:
            return self.print_time, eventtime, True
        return eventtime - 1., eventtime, True


class FakeHeaters:
    def __init__(self, heaters):
        self.heaters = heaters

    def lookup_heater(self, name):
        return self.heaters[name]


class FakeGcode:
    def __init__(self):
        self.commands = {}

    def register_command(self, name, func, desc=None):
        self.commands[name] = func


class FakePrinter:
    def __init__(self, reactor, objects):
        self.reactor, self.objects = reactor, objects
        self.handlers = {}

    def get_reactor(self):
        return self.reactor

    def lookup_object(self, name, default=None):
        return self.objects.get(name, default)

    def register_event_handler(self, event, callback):
        self.handlers[event] = callback


class FakeConfig:
    def __init__(self, printer):
        self.printer = printer

    def get_printer(self):
        return self.printer

    def get_name(self):
        return 'gcode_preprocessor heat_stats'


class RuntimeTests(unittest.TestCase):
    def setUp(self):
        self.reactor = FakeReactor()
        self.t0 = FakeHeater(225., 225.)
        self.t1 = FakeHeater(125., 125.)
        self.toolhead = FakeToolhead()
        printer = self.printer = FakePrinter(self.reactor, {
            'gcode': FakeGcode(),
            'heaters': FakeHeaters({'extruder': self.t0, 'extruder1': self.t1}),
            'toolhead': self.toolhead,
        })
        self.runtime = heat_stats.HeatStatsRuntime(FakeConfig(printer), {'history_file': ''})
        printer.handlers['klippy:ready']()

    def heat(self, heater, until, rate=3.):
        """Advance time in 0.1 s steps while the heater moves toward its target"""
        while self.reactor.now < until - 1e-9:
            step = min(.1, until - self.reactor.now)
            if heater.temp < heater.target:
                heater.temp = min(heater.target, heater.temp + rate * step)
            self.reactor.advance(self.reactor.now + step)

    def test_wait_and_suggestions(self):
        rt = self.runtime
        rt.reset()
        # Slicer preheat 15 s before the change: 125 -> 225 at 3 °C/s needs 33.3 s
        rt.preheat(1, self.reactor.now, 15.)
        self.t1.target = 225.
        self.heat(self.t1, 15.)
        rt.begin(1, self.reactor.now)
        self.heat(self.t1, 20.)                 # dock moves
        self.toolhead.moving = False            # M109 at the dock blocks
        self.heat(self.t1, 34.)
        rt.end(1, self.reactor.now)
        self.toolhead.moving = True

        record = rt.records[0]
        self.assertAlmostEqual(record['standstill'], 14., delta=.3)
        self.assertAlmostEqual(record['wait'], 12.9, delta=.3)   # until within 1 °C
        self.assertAlmostEqual(record['real_lead'], 15., delta=.01)
        s = rt.summary()['tools'][1]
        self.assertAlmostEqual(s['heat_rate'], 3.08, delta=.1)
        # 15 s + p90 wait (12.8 s) + 3 s margin = 30.8 -> 31
        self.assertEqual(s['suggest_preheat'], 31)
        # available 32.8 s - 12.8 s = 20 s -> 3.03 * 20 * 0.9 = 54.5 -> -50 °C
        self.assertEqual(s['suggest_standby_delta'], -50.)
        self.assertEqual(s['suggest_idle_temp'], 175.)
        text = rt.report(save=False)
        self.assertIn('preheat_time: 31 s', text)
        self.assertIn('standby_temperature_delta: -50 °C', text)
        self.assertNotIn(1, rt.tracks)

    def test_preheat_undone_by_cooldown(self):
        rt = self.runtime
        rt.reset()
        # Preheat for T0 while T0 still prints at 225 °C, then the slicer cooldown
        rt.preheat(0, self.reactor.now, 15.)
        self.heat(self.t0, 2.)
        self.t0.target = 125.
        self.t0.temp = 215.
        self.heat(self.t0, 4.)
        self.assertEqual(rt.cancelled, {0: 1})
        # Reheat at the change, no preheat lead counted
        self.t0.target = 225.
        rt.begin(0, self.reactor.now)
        self.toolhead.moving = False
        self.heat(self.t0, 8.)
        rt.end(0, self.reactor.now)
        record = rt.records[0]
        self.assertIsNone(record['lead'])
        self.assertGreater(record['wait'], 2.)
        s = rt.summary()['tools'][0]
        self.assertEqual(s['cancelled_preheats'], 1)
        self.assertIsNone(s['suggest_preheat'])
        self.assertIn('preheats undone by cooldown: 1', rt.report(save=False))

    def test_no_wait_suggests_shorter_preheat(self):
        rt = self.runtime
        rt.reset()
        rt.preheat(1, self.reactor.now, 60.)
        self.t1.target = 225.
        self.heat(self.t1, 60.)                 # hot after 33 s, 27 s early
        rt.begin(1, self.reactor.now)
        self.heat(self.t1, 66.)
        rt.end(1, self.reactor.now)
        s = rt.summary()['tools'][1]
        self.assertEqual(s['wait_total'], 0.)
        # 60 - (27 s slack - 3 s margin) = 36
        self.assertEqual(s['suggest_preheat'], 36)

    def test_settle_time_counts_as_wait(self):
        rt = self.runtime
        rt.reset()
        # Nozzle already within 1 °C, but M109 still waits for the PID to settle
        self.t1.target, self.t1.temp = 225., 224.5
        self.t1.settled_at = 3.
        rt.begin(1, self.reactor.now)
        self.toolhead.moving = False
        self.heat(self.t1, 5.)
        rt.end(1, self.reactor.now)
        record = rt.records[0]
        self.assertAlmostEqual(record['wait'], 3., delta=.3)
        self.assertAlmostEqual(record['standstill'], 5., delta=.3)

    def test_print_time_resync_is_standstill(self):
        rt = self.runtime
        rt.reset()
        self.t1.target = 225.
        rt.begin(1, self.reactor.now)
        self.toolhead.moving = False
        # Mainline Klipper's M109 loop moves print_time 0.25 s ahead every second
        for second in range(5):
            self.toolhead.print_time = self.reactor.now + .25
            self.printer.handlers['toolhead:sync_print_time'](
                self.reactor.now, self.reactor.now, self.toolhead.print_time)
            self.heat(self.t1, self.reactor.now + 1.)
        rt.end(1, self.reactor.now)
        self.assertAlmostEqual(rt.records[0]['standstill'], 5., delta=.3)

    def test_timer_stops_without_tracks(self):
        rt = self.runtime
        rt.reset()
        rt.begin(1, self.reactor.now)
        rt.end(1, self.reactor.now + .1)
        self.reactor.advance(self.reactor.now + 1.)
        self.assertEqual(rt.timer[1], FakeReactor.NEVER)
        self.assertIsNone(rt.last_sample)

    def test_history_file(self):
        path = os.path.join(tempfile.mkdtemp(), 'stats.jsonl')
        try:
            self.runtime.history_file = path
            self.runtime.reset()
            self.runtime.begin(1, 0.)
            self.runtime.end(1, 1.)
            self.runtime.report()
            with open(path) as f:
                self.assertEqual(len(f.readlines()), 1)
        finally:
            shutil.rmtree(os.path.dirname(path))


class SummaryTests(unittest.TestCase):
    def test_empty(self):
        self.assertEqual(heat_stats.format_report(heat_stats.summarize([])),
                         "KTC heat stats: no tool changes measured")

    def test_global_values(self):
        def rec(tool, wait):
            # heat from 125 to 225 at 4 °C/s = 25 s
            return {'tool': tool, 'wait': wait, 'standstill': wait, 'duration': 10. + wait,
                    'target': 225., 'begin_temp': 150., 'lead': 15., 'real_lead': 15.,
                    'heat_start': -15., 'heat_start_temp': 125., 'heat_reached': 10.}
        summary = heat_stats.summarize([rec(0, 10.), rec(2, 4.)])
        # Longest preheat and smallest standby drop win
        self.assertEqual(summary['suggest_preheat'], 28)       # 15 + 10 + 3
        self.assertEqual(summary['tools'][2]['suggest_preheat'], 22)
        self.assertEqual(summary['suggest_standby_delta'], -50.)  # 4 * (25 - 10) s * 0.9 = 54
        self.assertEqual(summary['tools'][2]['suggest_standby_delta'], -75.)


